# -*- coding: utf-8 -*-
"""Собирает indicator/КАРТОЧКИ.md из research/out/cards_v2.csv."""
import csv, io
G=list(csv.DictReader(open('research/out/cards_v2.csv',encoding='utf-8-sig')))
for r in G:
    r['точка']=int(r['точка']); r['сделок']=int(r['сделок'])
    for k in ('сыройR','надбавка','шум2s','база'): r[k]=float(r[k])
o=io.StringIO(); W=o.write
W("""# Четыре карточки входа

Один рабочий слой **3/3**. Свеча появилась — смотрим, на какой точке счёта
стоим и куда счёт идёт, дальше по карточке.

## Параметры, на которых всё посчитано

| | |
|---|---|
| рабочий слой | 3/3 · глубина пробоя 0.33 · рывок 0.5 · пауза 2 метки |
| сигнал | триггерная свеча, 40 шаблонов, допуск ±4% |
| вход | по закрытию свечи |
| стоп | за экстремум триггерной свечи, буфер 0.1% |
| цель | ближайшее непробитое колено 3/3 нужной стороны с плечом ≥ 3 |
| ведение | до стопа или цели · оба в одном баре = стоп · ждём максимум 1500 баров |
| фильтры движка | сняты — их место занимают карточки |

Непробитое колено — то, чью цену рынок с момента подтверждения не проходил.
Правило движка: уровень живёт, пока не пробит.

## Как читать клетку

**Надбавка** — сколько точка добавила к слепому входу в ту же сторону.
Считаем от неё, а не от сырого результата: за два года золото прошло +79%,
и по сырому R любой лонг вышел бы «можно».

Вердикт ставится только когда выполнено всё сразу:

* сделок не меньше 30
* надбавка больше двух сигм
* знак надбавки одинаковый в обеих половинах истории

Иначе — «нейтрально»: точка ничего не добавила и ничего не отняла.

---
""")
def card(tf,side,nm):
    rs=[r for r in G if r['тф']==tf and r['сторона']==side]
    if not rs: return
    W(f"\n## {tf} · {nm}\n\nСлепой вход в эту сторону **{rs[0]['база']:+.2f}R**.\n\n")
    W("| точка | счёт | вердикт | сделок | надбавка |\n|---|---|---|---|---|\n")
    for cn in range(6):
        for d in ('вверх','вниз'):
            r=next((x for x in rs if x['точка']==cn and x['счёт']==d),None)
            if not r: continue
            v=r['вердикт']
            mark={'МОЖНО':'**МОЖНО**','НЕЛЬЗЯ':'**НЕЛЬЗЯ**'}.get(v,v)
            W(f"| **({cn})** | {d} {'↑' if d=='вверх' else '↓'} | {mark} | {r['сделок']} | "
              f"{r['надбавка']:+.2f}R ± {r['шум2s']:.2f} |\n")
for tf in ('1H','5m'):
    card(tf,'LONG','ЛОНГ'); card(tf,'SHORT','ШОРТ')
W("""
---

# Что карточки говорят

Из 48 клеток вердикт получили **семь**. Случайно при таком пороге прошла бы
примерно одна. То есть это не совпадение.

| тф | сторона | точка | счёт | вердикт | сделок | надбавка |
|---|---|---|---|---|---|---|
| 1H | ЛОНГ | (0) | вверх ↑ | НЕЛЬЗЯ | 203 | −0.58R ± 0.25 |
| 1H | ШОРТ | (4) | вверх ↑ | НЕЛЬЗЯ | 106 | −0.58R ± 0.28 |
| 1H | ШОРТ | (5) | вверх ↑ | НЕЛЬЗЯ | 51 | −0.74R ± 0.27 |
| 5m | ЛОНГ | (2) | вниз ↓ | НЕЛЬЗЯ | 350 | −0.34R ± 0.23 |
| 5m | ЛОНГ | (3) | вниз ↓ | НЕЛЬЗЯ | 173 | −0.34R ± 0.30 |
| 5m | ЛОНГ | (5) | вверх ↑ | НЕЛЬЗЯ | 55 | −0.59R ± 0.59 |
| 5m | ЛОНГ | (4) | вниз ↓ | МОЖНО | 103 | +0.69R ± 0.68 |

**Шесть из семи — запреты, и они складываются в одну картину.**

Шорт на (4) и (5) счёта вверх — это вход против зрелого счёта, в тот момент,
когда движение уже показало себя. Лонг на (2) и (3) счёта вниз — то же самое
зеркально. Карточка говорит: не входить против счёта в его середине и конце.

Лонг на (0) счёта вверх — отдельный случай. Точка (0) это самое начало,
где ещё ничего не подтверждено. Совпадает с тем, что вы сами говорили:
на (0) тяжело принять решение и лонг допустим только при сильном условии.

**Единственное разрешение слабое.** Лонг на (4) счёта вниз, +0.69R при шуме
±0.68 — ровно на границе. И оно не согласуется с соседним запретом на (2)
того же счёта, хотя обе точки чётные, то есть коррекционные. Записывать в
рабочее правило рано.

# Контекст 5/5 в простом виде не работает

Меряли отдельно, все точки вместе: помогает ли согласие тренда 5/5 со
стороной сделки.

| тф | сторона | тренд 5/5 | сделок | надбавка | вердикт |
|---|---|---|---|---|---|
| 1H | ЛОНГ | согласен | 527 | −0.33R ± 0.21 | **НЕЛЬЗЯ** |
| 1H | ЛОНГ | против / нет | 803 | +0.22R ± 0.26 | нейтрально |
| 1H | ШОРТ | согласен | 716 | +0.23R ± 0.27 | нейтрально |
| 1H | ШОРТ | против / нет | 1480 | −0.11R ± 0.19 | нейтрально |
| 5m | ЛОНГ | согласен | 990 | +0.00R ± 0.18 | нейтрально |
| 5m | ЛОНГ | против / нет | 2000 | −0.00R ± 0.12 | нейтрально |
| 5m | ШОРТ | согласен | 1138 | −0.00R ± 0.18 | нейтрально |
| 5m | ШОРТ | против / нет | 1765 | +0.00R ± 0.15 | нейтрально |

На 5m контекст не даёт ровно ничего — все четыре строки нули.

На 1H он даёт обратное ожидаемому: лонг **при согласном** тренде 5/5 хуже
слепого входа на 0.33R, а лонг против тренда 5/5 лучше на 0.22R.

Этому есть механическое объяснение, и его надо проверить, прежде чем
делать вывод о рынке. Цель — ближайшее **непробитое** колено сверху.
Когда 5/5 растёт, цена обновляет максимумы, непробитых колен над ней почти
не остаётся, и целью становится что-то далёкое и труднодостижимое. Когда
5/5 падает, над ценой полно непробитых вершин, и цель близкая. То есть
разница может быть свойством правила цели, а не свойством тренда.

Так что в условие входа контекст 5/5 в этом виде **не ставим**.
""")
open('indicator/КАРТОЧКИ.md','w',encoding='utf-8').write(o.getvalue())
print('indicator/КАРТОЧКИ.md готов')
