# -*- coding: utf-8 -*-
"""НИЧЬИ СЫРЫХ ПИВОТОВ слоя 2/2 — подсчёт по замечанию З36.

Повод: его слово 29.10.2026 «посчитай сколько таких случаев».

ЧТО СЧИТАЕТСЯ. Сырой пивот `ta.pivothigh(2,2)` / `ta.pivotlow(2,2)`,
цена которого РОВНО равна цене ПРЕДЫДУЩЕГО сырого пивота той же
стороны. В пайне (строки 2749-2756) оба условия подписи тогда ложны:
подписи нет, значит по `ПРАВИЛА-СЛОМ.md` §1 нет и уровня.

Пивоты берутся функцией `pivots_by_bar` из `dvizhok2.py` — той же, что
кормит движок (слева <=, справа <). Своей копии тут нет нарочно.
Движок на сырые пивоты не влияет вовсе: они считаются до него.

ЧИСЛА ПО КОЛЕНАМ ТУТ НЕ СЧИТАЮТСЯ, и это нарочно. Колено — другое
население (сырой пивот ПОСЛЕ схлопывания соседей одной стороны), и
массив колен в реплике обрезан до MAXK=100, как в пайне, так что по нему
считать нельзя. Ничьи колен даёт `zerkalo_check.py`: на слое 2/2 это
3 за девять лет, 0 за два года, 4 на пятиминутке.

ВТОРАЯ ЧАСТЬ — ПРОВЕРКА УРОВНЯ. Первая запись разбора 29.10 утверждала,
что на ничьей «слом по этой цене не произойдёт никогда». ЭТО БЫЛО
НЕВЕРНО, и проверка ниже это показала: уровень по той же цене ставит
ПРЕДЫДУЩИЙ пивот, а `f_purgeL` вычёркивает его касанием — то есть ровно
на баре второго пивота. Слом состоится, не появится лишь НОВАЯ линия.
"""

import os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(root, 'research'))

from core import load
import dvizhok2 as D


def nichyi(rows):
    """Ничьи сырых пивотов 2/2 плюс судьба уровня по той же цене."""
    hi = [r[2] for r in rows]
    lo = [r[3] for r in rows]
    H, L = D.pivots_by_bar(rows, 2)
    out = {}
    for nm, P, isHi in (('вершины', H, True), ('низы', L, False)):
        bars = sorted(P)
        cases = []
        for k in range(1, len(bars)):
            b, a = bars[k], bars[k - 1]
            if P[b] != P[a]:
                continue
            pr = P[b]
            aprev = P[bars[k - 2]] if k >= 2 else None
            born = a + 2                      # уровень A попадает в список
            kill = None
            for i in range(born, len(rows)):
                if (hi[i] >= pr) if isHi else (lo[i] <= pr):
                    kill = i
                    break
            cases.append(dict(bar=b, pr=pr, a=a, born=born, kill=kill,
                              a_lab=(aprev is not None and aprev != pr)))
        out[nm] = dict(всего=len(bars), случаи=cases, первый=1 if bars else 0)
    return out


NABORY = (
    ('часовик, девять лет', 'data/XAUUSD_1h_9y.csv'),
    ('часовик, два года',   'data/XAUUSD_1h_2y.csv'),
    ('пятиминутка',         'data/XAUUSD_5m.csv'),
)

print('НИЧЬИ СЫРЫХ ПИВОТОВ слоя 2/2 — замечание З36')
print('=' * 78)

itog = []
for nm, path in NABORY:
    rows = load(os.path.join(root, path))
    s = nichyi(rows)
    tot = s['вершины']['всего'] + s['низы']['всего']
    cs = s['вершины']['случаи'] + s['низы']['случаи']
    print('\n%s — %d баров, с %s по %s'
          % (nm, len(rows), rows[0][0][:10], rows[-1][0][:10]))
    print('  сырых пивотов 2/2        %6d   (вершин %d, низов %d)'
          % (tot, s['вершины']['всего'], s['низы']['всего']))
    print('  из них НИЧЬЯ             %6d   %.3f%%   (вершин %d, низов %d)'
          % (len(cs), 100.0 * len(cs) / tot if tot else 0,
             len(s['вершины']['случаи']), len(s['низы']['случаи'])))
    print('  плюс самый первый каждой стороны  2 — уровня тоже нет')
    itog.append((nm, tot, len(cs)))
    for sd in ('вершины', 'низы'):
        for c in s[sd]['случаи']:
            print('    %-8s %9.2f  второй пивот бар %-6d  прежний бар %-6d  '
                  'подпись у прежнего %s  уровень жил с бара %-6d  '
                  'вычеркнут на баре %-6s  %s'
                  % (sd[:-1], c['pr'], c['bar'], c['a'],
                     'ЕСТЬ' if c['a_lab'] else 'НЕТ',
                     c['born'], c['kill'],
                     'РОВНО на баре второго пивота' if c['kill'] == c['bar']
                     else 'РАНЬШЕ второго пивота' if c['kill'] is not None
                     and c['kill'] < c['bar'] else 'позже — разобрать'))

print('\n' + '=' * 78)
print('ИТОГ')
for nm, tot, n in itog:
    print('  %-22s  пивотов %6d   ничьих %3d   %.3f%%'
          % (nm, tot, n, 100.0 * n / tot if tot else 0))
print('''
ЧТО ТЕРЯЕТСЯ НА НИЧЬЕЙ. Не слом: уровень по той же цене уже стоял от
предыдущего пивота и вычёркивается касанием ровно на баре второго — слом
фиксируется, f_slom вызывается ДО f_lvPush. Теряется НОВАЯ линия: второй
пивот не оставляет уровня по этой цене, и будущий приход цены туда
сломом считаться не будет.''')
