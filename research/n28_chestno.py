def zahod(rows, hist, a, b, flip):
    """Самое глубокое захождение ниже колена на барах (a, b].
    Цена колена берётся НА КАЖДЫЙ БАР (вариант Б).
    Возвращает (по телу, по тени) в ценах, 0 если захода не было."""
    dt = dsh = 0.0
    for i in range(max(a + 1, 0), min(b + 1, len(rows))):
        pr = O.cena(hist, i)
        if pr is None:
            continue
        _, o, h, l, c = rows[i]
        if flip:
            o, h, l, c = -o, -l, -h, -c
        telo = min(o, c)
        if telo < pr:
            dt = max(dt, pr - telo)
        if l < pr:
            dsh = max(dsh, pr - l)
    return dt, dsh


def sobral(res, rows, flip):
    C = res['C'][2]
    legs = res['sl_leg']
    TR = res['T'][2].TR
    n = len(C.P)
    # единица Н28: ОДНО среднее колено за весь прогон
    nogi = [abs(C.P[i] - C.P[i - 1]) for i in range(1, n)]
    avg = sum(nogi) / len(nogi) if nogi else 1.0
    out = []
    for k in range(n - 3):
        if C.H[k]:
            continue                        # сторож — НИЗ
        # цепочка чередуется: k низ, k+1 вершина, k+2 низ, k+3 вершина
        if C.H[k + 1] and (not C.H[k + 2]) and C.H[k + 3]:
            pass
        else:
            continue
        fk, fn, fv = C.FC[k], C.FC[k + 2], C.FC[k + 3]
        if fn <= fk or fv <= fn or fv >= len(rows):
            continue
        leg = legs[fk] if fk < len(legs) else 0.0
        if not leg or leg <= 0:
            continue
        dt, dsh = zahod(rows, C.HIST[k], fk, fn, flip)
        cnt = TR[fk][2] if fk < len(TR) else -1
        out.append({'telo': dt / leg, 'ten': dsh / leg,
                    'telo28': dt / avg, 'ten28': dsh / avg,
                    'opravil': C.FL[k + 3] == 'HH',
                    'gryazno': C.L[k + 3] == 'HH',
                    'cnt': cnt,
                    'z28': C.FL[k + 2] == 'LL',
                    'zwide': dsh > 0})
    return out


def odna(sel, key, pole, pnm):
    a = [r[pole] for r in sel if r[key]]
    b = [r[pole] for r in sel if not r[key]]
    if len(a) < 20 or len(b) < 20:
        return None
    ma, mb = st.median(a), st.median(b)
    raz = mb / ma if ma > 0 else float('inf')
    print('       %-14s оправился %.3f (%4d)   слабеет %.3f (%4d)   в %s раз'
          % (pnm, ma, len(a), mb, len(b),
             ('%.1f' % raz) if raz != float('inf') else '∞'))
    return raz


