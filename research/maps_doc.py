# -*- coding: utf-8 -*-
"""Генерирует indicator/КАРТЫ-ВХОДА.md из research/out/maps_grid.csv."""
import csv, collections, math, io

G = list(csv.DictReader(open('research/out/maps_grid.csv', encoding='utf-8-sig')))
for r in G:
    r['сделок'] = int(r['сделок']); r['точка'] = int(r['точка']); r['счёт'] = int(r['счёт'])
    for k in ('EV','шум2s','EV_1половина','EV_2половина'): r[k] = float(r[k])

base = collections.defaultdict(lambda: [0.0, 0])
for r in G:
    k = (r['тф'], r['слой'], r['сторона'], r['стоп'], r['цель'])
    base[k][0] += r['EV'] * r['сделок']; base[k][1] += r['сделок']
B = {k: (v[0]/v[1] if v[1] else 0.0, v[1]) for k, v in base.items()}

# устойчивые клетки: 2 сигмы минимум в 3 из 9 комбинаций «стоп x цель», один знак
agg = collections.defaultdict(list)
for r in G:
    if r['сделок'] < 25: continue
    bs = B[(r['тф'], r['слой'], r['сторона'], r['стоп'], r['цель'])][0]
    agg[(r['тф'],r['слой'],r['счёт'],r['точка'],r['сторона'])].append(
        (r['EV']-bs, r['шум2s'], r['EV_1половина']-bs, r['EV_2половина']-bs))
ROB = {}
for k, v in agg.items():
    sig = [x for x in v if abs(x[0]) > x[1] > 0]
    if len(sig) < 3: continue
    if not (all(x[0] > 0 for x in sig) or all(x[0] < 0 for x in sig)): continue
    m = sum(x[0] for x in sig)/len(sig)
    h1 = sum(x[2] for x in sig)/len(sig); h2 = sum(x[3] for x in sig)/len(sig)
    ROB[k] = (m, len(sig), (h1 > 0 and h2 > 0) or (h1 < 0 and h2 < 0))

STOP, TGT = 'колено', '3R'
o = io.StringIO()
W = o.write

W("""# Восемь карт входа

Что здесь: для каждой связки **таймфрейм · слой меток · сторона сделки**
таблица «на какой точке счёта что даёт вход».

Мерялось так: появилась триггерная свеча, слой стоит на точке N счёта,
идущего вверх или вниз — открываем сделку в заданную сторону, стоп за
последним коленом слоя (буфер 0.1%), цель 3R. Считаем R на сделку.

Источник: `research/maps.py`, полная сетка на 826 строк —
`research/out/maps_grid.csv` (три варианта стопа x три варианта цели).

---

## Сначала — ловушка, из-за которой сырые карты врут

За два года золото на 1H прошло **+79%** (2458 → 4406). За 3.5 месяца
на 5m — **−2.9%** (4561 → 4427).

В сыром виде это даёт вот что:

| | вход ЛОНГ вслепую | вход ШОРТ вслепую |
|---|---|---|
| **1H** | **+0.37R … +0.41R** | −0.20R … −0.23R |
| **5m** | −0.07R … −0.12R | **+0.13R … +0.14R** |

То есть на часовке в плюсе любой лонг, а на пятиминутке любой шорт —
и точка счёта тут ни при чём. Если этого не убрать, «карта» окажется
просто пересказом того, куда шёл рынок в выборке.

**Убирается так:** каждая клетка показывается как **надбавка** к слепому
входу в ту же сторону. Снос добавляет одно и то же всем лонгам и всем
шортам, вычитание базы его убирает.

Дальше во всех восьми картах числа — именно надбавка.
Ноль означает «точка не добавила ничего к слепому входу».

---
""")

def table(tf, layer, side):
    W(f"\n## {tf} · метки {layer} · {side}\n\n")
    bs, bn = B.get((tf, layer, side, STOP, TGT), (0.0, 0))
    W(f"Слепая база для этой стороны: **{bs:+.2f}R** на {bn} сделках.\n\n")
    W("| точка | счёт ВВЕРХ ↑ | счёт ВНИЗ ↓ |\n|---|---|---|\n")
    sel = {(r['счёт'], r['точка']): r for r in G
           if r['тф']==tf and r['слой']==layer and r['сторона']==side
           and r['стоп']==STOP and r['цель']==TGT}
    for cn in range(6):
        cells = []
        for cd in (1, -1):
            r = sel.get((cd, cn))
            if r is None or r['сделок'] < 25:
                cells.append('—'); continue
            d = r['EV'] - bs
            rb = ROB.get((tf, layer, cd, cn, side))
            tag = ''
            if rb: tag = ' **✔**' if rb[2] else ' ~'
            cells.append(f"{d:+.2f}R ± {r['шум2s']:.2f} · {r['сделок']} сд{tag}")
        W(f"| **({cn})** | {cells[0]} | {cells[1]} |\n")
    rob = [(k, v) for k, v in ROB.items() if k[0]==tf and k[1]==layer and k[4]==side]
    if rob:
        W("\nУстойчивые клетки этой карты:\n\n")
        for k, v in sorted(rob, key=lambda x: x[0][3]):
            arrow = '↑' if k[2] == 1 else '↓'
            W(f"* счёт {arrow}, точка **({k[3]})** → надбавка **{v[0]:+.2f}R**, "
              f"держится в {v[1]} из 9 комбинаций стопа и цели, "
              f"{'знак одинаковый в обеих половинах истории' if v[2] else 'половины истории разошлись — не верить'}\n")
    else:
        W("\nУстойчивых клеток нет: ни одна точка не пережила смену стопа и цели.\n")
    W("\n")

for tf in ('1H', '5m'):
    W(f"\n# ═══ {tf} ═══\n")
    for layer in ('5/5', '2/2'):
        for side in ('LONG', 'SHORT'):
            table(tf, layer, side)

W("""
---

# Что говорят все восемь карт вместе

## 1 · Точка счёта сама по себе почти ничего не добавляет

Из 94 проверенных клеток два сигма-порога и смену стопа с целью
пережили **девять**, и семь из них устойчивы по половинам истории:

| тф | слой | счёт | точка | сторона | надбавка | комбинаций |
|---|---|---|---|---|---|---|
""")
for k, v in sorted(ROB.items(), key=lambda x: (x[0][0], x[0][1], x[0][3])):
    if not v[2]: continue
    W(f"| {k[0]} | {k[1]} | {'↑' if k[2]==1 else '↓'} | ({k[3]}) | {k[4]} | **{v[0]:+.2f}R** | {v[1]}/9 |\n")
W("""
**Восемь из девяти — запреты, а не разрешения.** Карта в её нынешнем виде
умеет говорить «здесь не лезь» и почти не умеет говорить «здесь заходи».
Единственная устойчивая положительная клетка — 1H, 5/5, счёт вниз,
точка (4), в ЛОНГ.

## 2 · Стоп решает больше, чем вся карта

Полусумма лонга и шорта убирает снос рынка и показывает, что даёт сама
пара «стоп + цель», без всякого счёта:

| 1H · слой 5/5 | магнит | 3R | 2R |
|---|---|---|---|
| стоп за **свечой** | +0.02 ± 0.07 | +0.03 ± 0.05 | +0.00 ± 0.04 |
| стоп за **коленом** | −0.04 ± 0.08 | **+0.09 ± 0.06** | +0.04 ± 0.05 |
| стоп за **уровнем тренда** | **+0.14 ± 0.13** | **+0.13 ± 0.09** | +0.04 ± 0.07 |

| 1H · слой 2/2 | магнит | 3R | 2R |
|---|---|---|---|
| стоп за **свечой** | +0.04 ± 0.07 | +0.03 ± 0.05 | +0.00 ± 0.04 |
| стоп за **коленом** | +0.04 ± 0.08 | **+0.09 ± 0.06** | +0.04 ± 0.05 |
| стоп за **уровнем тренда** | −0.01 ± 0.13 | +0.03 ± 0.09 | +0.02 ± 0.07 |

Стоп за экстремумом свечи — тот, что стоит в вашем движке и во всех моих
прежних замерах — **худший из трёх и неотличим от нуля**. Перенос стопа
за колено или за уровень тренда стоит примерно **+0.06 … +0.10R** на
сделку. Это больше, чем даёт любая клетка карты, кроме одной.

На 5m ни одна пара «стоп + цель» не отличима от нуля.

## 3 · Пятиминутка пока не выборка

3.5 месяца — один режим рынка. Сделок хватает (3189 триггерных свечей),
но проверить, повторится ли что-то в другом режиме, не на чем. Всё, что
на 5m выглядит значимым, может оказаться свойством этих конкретных
трёх месяцев. Это открытый вопрос О6.

---

# Чего не хватает, чтобы карты стали рабочими

**1. Вашего стопа.** Три варианта, которые я перебрал, — мои догадки.
Разброс между худшим и лучшим +0.10R на сделку, то есть выбор стопа
меняет карту сильнее, чем сама карта. Нужно, где вы его ставите.

**2. Вашего списка.** Карта из шести точек — это шесть ячеек, в каждой
сотни сделок вперемешку. Список признаков разрежет каждую ячейку на
«эти берём» и «эти пропускаем». Без него карта усредняет хорошее
с плохим и показывает ноль — что она сейчас и показывает.

**3. Целей помимо 3R.** Вы называли для чётных точек «минимум 1:3
и перебитие LH/HH» — это магнит, он померен. Для нечётных «1:2» —
померено. Если целей больше, назовите.
""")

open('indicator/КАРТЫ-ВХОДА.md', 'w', encoding='utf-8').write(o.getvalue())
print('indicator/КАРТЫ-ВХОДА.md готов')
