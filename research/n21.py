# -*- coding: utf-8 -*-
"""ПЕРЕСЧЁТ Н21 и Н24 НА ДОЗЕ 1.

Повод — просьба владельца 06.10.2026: «пересчитай Н21 на дозе 1».

ЗАЧЕМ. Н21 и Н24 были посчитаны при дозе «без ограничения», которая
была эталоном на 01.10.2026 и отменена владельцем 06.10.2026. При той
дозе все три слоя берут ОДИН И ТОТ ЖЕ набор колен (вывод Н22: 2569 на
каждом из трёх) и различаются только запаздыванием. Значит «совпало на
трёх слоях» там весило меньше, чем выглядело.

На дозе 1 слои расходятся: 1750 / 2341 / 2569 колен. Три слоя снова
становятся тремя разными выборками.

ЧТО СЧИТАЕТСЯ — ровно то же, что считалось тогда, менялась ТОЛЬКО доза:

  Н21 · линия НУЛЯ и линия низа (2), снятые СТРОГО ДО бара, на котором
        подтвердилось колено (3). Три состояния: цело · проколото тенью ·
        закрыто за линией. Исход — дошёл ли счёт ПОТОМ до (5).
        Вершина (1) — контроль, у неё пробой ожидается ВВЕРХ.

  Н24 · подпись низа (2): HL против LL, и доля дошедших до (5).
        Защита от тавтологии: клетка считается, только если счёт
        действительно дошёл до (2).

ДОНОР. На дозе 1 «только 3/3» и «3/3, а если пусто — 2/2» СОВПАДАЮТ:
запасной донор в Пайне заперт флагом «3/3 уже дал вставку в этой ноге»,
а одна вставка и так исчерпывает дозу. Поэтому donor = [3, 2] здесь и
есть эталон владельца.

ДВИЖОК: колена со вставками, доза 1, донор 5/5 — [3, 2], 3/3 — [2],
2/2 — свои. Смерть «имп × 0.33». Правила, принятые 05–06.10, НЕ входят.

    python3 research/n21.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from core import load
from forma import analyse

LAYERS = (('5/5', 5, [3, 2]), ('3/3', 3, [2]), ('2/2', 2, []))
DOSE = 1


def pc(a, b):
    return '—' if b == 0 else '%.1f%% (%d)' % (100.0 * a / b, b)


def line_table(store, key, title, note):
    print('\n' + title)
    print('  ' + note)
    print('  %-5s %-4s %16s %16s %16s' % ('слой', 'напр', 'цело', 'проколото тенью', 'закрыто за линией'))
    for nm, _, _ in LAYERS:
        for dirn in ('↑', '↓'):
            res = store[(nm, dirn)]
            cells = []
            for st in ('цело', 'тень', 'закр'):
                sub = [r for r in res if r[key] == st]
                cells.append(pc(sum(1 for r in sub if r['do5']), len(sub)))
            print('  %-5s %-4s %16s %16s %16s' % (nm, dirn, *cells))


def main():
    for path, title in (('data/XAUUSD_1h_2y.csv', 'ДВА ГОДА — сравнимо с исходным Н21'),
                        ('data/XAUUSD_1h_9y.csv', 'ДЕВЯТЬ ЛЕТ — которых в Н21 не было')):
        rows = load(path)
        print('\n' + '=' * 82)
        print('%s · %d баров · ДОЗА %d' % (title, len(rows), DOSE))
        print('=' * 82)
        store = {}
        for nm, dL, dDs in LAYERS:
            for flip, dirn in ((False, '↑'), (True, '↓')):
                res, _, _, nk = analyse(rows, nm, dL, dDs, flip, DOSE)
                store[(nm, dirn)] = res
        line_table(store, 'z', 'Н21 · ЛИНИЯ НУЛЯ до прихода (3)',
                   'доля счётов, дошедших ПОТОМ до (5). Пробой ждём ВНИЗ')
        line_table(store, 'n2', 'Н21 · ЛИНИЯ НИЗА (2) до прихода (3)',
                   'то же. Пробой ждём ВНИЗ')
        line_table(store, 'v1', 'Н21 · ВЕРШИНА (1) до прихода (3) — КОНТРОЛЬ',
                   'то же, но пробой ждём ВВЕРХ: у вершины «закрыто ЗА линией» = выше')

        print('\nН24 · ПОДПИСЬ НИЗА (2): HL против LL')
        print('  считаются только счёты, реально дошедшие до (2)')
        print('  %-5s %-4s %18s %18s %10s' % ('слой', 'напр', 'низ (2) = HL', 'низ (2) = LL', 'разрыв'))
        for nm, _, _ in LAYERS:
            for dirn in ('↑', '↓'):
                res = [r for r in store[(nm, dirn)] if r['mx'] >= 2 and r['ntail'] >= 2]
                g = {}
                for lab in ('HL', 'LL'):
                    sub = [r for r in res if r['tail'].split('·')[1] == lab]
                    g[lab] = (sum(1 for r in sub if r['do5']), len(sub))
                d = ('%+.1f пп' % (100.0 * g['HL'][0] / g['HL'][1] - 100.0 * g['LL'][0] / g['LL'][1])
                     if g['HL'][1] and g['LL'][1] else '—')
                print('  %-5s %-4s %18s %18s %10s' % (nm, dirn, pc(*g['HL']), pc(*g['LL']), d))


if __name__ == '__main__':
    main()
